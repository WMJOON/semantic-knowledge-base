def test_xsd_literal_clash_is_an_artifact_not_an_inconsistency():
    # 같은 어휘형 "1" 이 문자열과 숫자로 함께 쓰이면 owlrl 이 xsd:decimal/xsd:string disjoint 위반을 보고한다
    _, errors, artifacts = R.infer(g('ex:a ex:count 1 . ex:b ex:label "1" .'))
    assert errors == []
    assert R.split_errors(["Disjoint classes http://www.w3.org/2001/XMLSchema#decimal and http://www.w3.org/2001/XMLSchema#string have a common individual 1"])[1]


def test_literal_and_standard_vocabulary_subjects_are_not_inferred():
    inferred, _, _ = R.infer(g('ex:a ex:count 1 . ex:A a owl:Class .'))
    from rdflib import Literal, URIRef
    assert not any(isinstance(s, Literal) for s, _, _ in inferred)
    assert not any(isinstance(s, URIRef) and str(s).startswith("http://www.w3.org/") for s, _, _ in inferred)
    # 파생 TTL 은 직렬화해서 다시 읽을 수 있어야 한다
    Graph().parse(data=inferred.serialize(format="turtle"), format="turtle")


def test_cli_check_ignores_artifacts_unless_strict(tmp_path):
    root = kb(tmp_path, 'ex:a ex:count 1 . ex:b ex:label "1" .')
    base = ["--target", str(root), "--domain", "demo"]
    assert CLI.main(["check", *base]) == 0
